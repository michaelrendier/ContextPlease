#!/usr/bin/env python3
"""Two definition-level checks.
(1) SPINOR: a Clifford module needs L_a^2 = -|a|^2 for all imaginary a (then the L_{e_i} generate Cl_{0,n-1} acting on the space).
(2) BRAID: with phi = associator sign and beta = commutator sign, do both hexagon identities of a braided monoidal category hold?"""
import numpy as np, itertools
from common import *
rng = np.random.default_rng(4)
E = np.eye(16)
def clifford_defect(idx, n=40):
    w = 0.0
    for _ in range(n):
        a = np.zeros(16); a[idx] = rng.normal(size=len(idx))
        L = Lmat(a); w = max(w, np.abs(L @ L + (a @ a) * np.eye(16)).max())
    return w
low = list(range(1, 8)); allim = list(range(1, 16))
print("(1) SPINOR / Clifford-module test:  max | L_a L_a + |a|^2 I |  over random imaginary a")
print("    a in the lower octonion's imaginaries (indices 1..7):   %.2e   -> Clifford module Cl(0,7) on R^8 = the octonion spinor: %s" % (clifford_defect(low), clifford_defect(low) < 1e-9))
print("    a in the 7 imaginaries {1,2,3,8,9,10,11} (another sub-octonion): %.2e" % clifford_defect([1, 2, 3, 8, 9, 10, 11]))
print("    a in a NON-alternative hyperplane {2,4,6,9,11,13,15}: %.2e" % clifford_defect([2, 4, 6, 9, 11, 13, 15]))
print("    a in ALL 15 sedenion imaginaries:                        %.2e   -> the sedenions are NOT a Clifford module under their own left multiplication: %s" % (clifford_defect(allim), clifford_defect(allim) > 1e-6))
# the failure is exactly the non-alternativity: L_a L_a x - (a a) x = a(ax) + |a|^2 x
a = np.zeros(16); a[allim] = rng.normal(size=15); x = rng.normal(size=16)
print("    norm of the failure for one random a, x: |a(ax) + |a|^2 x| = %.3f" % np.linalg.norm(m(a, m(a, x)) + (a @ a) * x))

al = np.array([[T_[i, j, i ^ j] for j in range(16)] for i in range(16)])
beta = al / al.T
phi = np.zeros((16, 16, 16), int)
for i in range(16):
    for j in range(16):
        for k in range(16):
            l = m(m(E[i], E[j]), E[k]); r = m(E[i], m(E[j], E[k])); phi[i, j, k] = 1 if np.allclose(l, r) else -1
print("\n(2) BRAID: sign-valued associator phi(i,j,k) and braiding beta(i,j) = alpha(i,j)/alpha(j,i) on Z2^4")
b1 = b2 = 0
for i in range(16):
    for j in range(16):
        for k in range(16):
            h1 = phi[j, k, i] * beta[i, j ^ k] * phi[i, j, k] == beta[i, k] * phi[j, i, k] * beta[i, j]
            h2 = phi[k, i, j] * beta[i ^ j, k] * phi[i, j, k] == beta[i, k] * phi[i, k, j] * beta[j, k]
            b1 += (not h1); b2 += (not h2)
print("    hexagon 1:  phi(j,k,i) beta(i,j^k) phi(i,j,k) = beta(i,k) phi(j,i,k) beta(i,j)   violations over all 4096 (i,j,k): %d" % b1)
print("    hexagon 2:  phi(k,i,j) beta(i^j,k) phi(i,j,k) = beta(i,k) phi(i,k,j) beta(j,k)   violations over all 4096 (i,j,k): %d" % b2)
cob = 0
for i in range(16):
    for j in range(16):
        for k in range(16):
            cob += (phi[i, j, k] != al[i, j] * al[i ^ j, k] * al[j, k] * al[i, j ^ k])
print("    phi = coboundary of alpha:  phi(i,j,k) = alpha(i,j) alpha(i^j,k) alpha(j,k) alpha(i,j^k): violations %d" % cob)
print("    (if the hexagons hold, the multiplication table is an algebra in a braided monoidal category of Z2^4-graded spaces: braiding = commutator sign, associator = nonassociativity sign, both generated by the single cocycle alpha)")
print("    beta is not a bicharacter (2520 violations, genealogy.py), so this braiding is NOT the trivial/symmetric one: it is carried by the associator phi.")
