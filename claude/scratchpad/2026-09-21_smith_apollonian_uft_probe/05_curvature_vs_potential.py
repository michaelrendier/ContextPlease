# Realize the actual seed (-1,2,2,3) geometrically to check for genuine
# continuous freedom vs. the fixed +- two-fold choice.
def descartes_centers(k1, k2, k3, z1, z2, z3):
    ksum = k1 + k2 + k3
    inner = k1 * k2 * (z1 - z2) * (z1 - z2).conjugate()  # placeholder, real formula below
    # Correct complex Descartes (Lagarias-Mallows-Wilks 2002):
    term = cmath.sqrt(k1 * k2 * z1 * z2 + k2 * k3 * z2 * z3 + k3 * k1 * z3 * z1)
    z4a = (k1 * z1 + k2 * z2 + k3 * z3 + 2 * term) / ksum
    z4b = (k1 * z1 + k2 * z2 + k3 * z3 - 2 * term) / ksum
    return z4a, z4b


