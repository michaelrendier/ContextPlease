def schwarzian(f, s, h=1e-4):
    """Numerical Schwarzian derivative: (f'''/f') - 1.5*(f''/f')**2."""
    def d1(g, x): return (g(x + h) - g(x - h)) / (2 * h)
    def d2(g, x): return (g(x + h) - 2 * g(x) + g(x - h)) / (h ** 2)
    def d3(g, x):
        return (g(x + 2 * h) - 2 * g(x + h) + 2 * g(x - h) - g(x - 2 * h)) / (2 * h ** 3)
    fp = d1(f, s)
    fpp = d2(f, s)
    fppp = d3(f, s)
    return fppp / fp - 1.5 * (fpp / fp) ** 2


for s in (2.0 + 0j, 5.0 + 3j, -0.3 + 7j):
    S = schwarzian(gamma, s)
    print(f"    s={s}   Schwarzian(Gamma)(s) = {S:.2e}   (0 to float precision)")

